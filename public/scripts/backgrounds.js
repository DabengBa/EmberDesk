import { eventSource, event_types } from './events.js';
import {
    chat_metadata,
    saveSettingsDebounced,
} from '../script.js';
import { saveMetadataDebounced } from './extensions.js';

const BG_METADATA_KEY = 'custom_background';
const LIST_METADATA_KEY = 'chat_backgrounds';
const DEFAULT_BACKGROUND_NAME = '__transparent.png';
const DEFAULT_FITTING = 'classic';
const DEFAULT_SORT_ORDER = 'az';

/**
 * The settings object remains the compatibility boundary for the legacy
 * settings document. Unknown fields are intentionally retained on load.
 */
export let background_settings = {
    name: DEFAULT_BACKGROUND_NAME,
    url: generateUrlParameter(DEFAULT_BACKGROUND_NAME, false),
    fitting: DEFAULT_FITTING,
    animation: false,
    sortOrder: DEFAULT_SORT_ORDER,
    thumbnailColumns: 5,
};

/**
 * Return the browser path for a stored global background filename.
 * @param {string} fileUrl
 * @returns {string}
 */
export function getBackgroundPath(fileUrl) {
    const value = String(fileUrl ?? '');
    return value.startsWith('backgrounds/')
        ? value
        : `backgrounds/${encodeURIComponent(value)}`;
}

/**
 * Build the CSS URL used by the background renderer.
 * @param {string} bg
 * @param {boolean} isCustom
 * @returns {string}
 */
export function generateUrlParameter(bg, isCustom) {
    return isCustom ? `url("${encodeURI(String(bg ?? ''))}")` : `url("${getBackgroundPath(bg)}")`;
}

/**
 * Check whether a CSS URL identifies one of the current chat's custom files.
 * @param {string} fileUrl
 * @returns {boolean}
 */
export function isCustomBackgroundUrl(fileUrl) {
    const customBackgrounds = Array.isArray(chat_metadata[LIST_METADATA_KEY])
        ? chat_metadata[LIST_METADATA_KEY]
        : [];
    const value = String(fileUrl ?? '');
    return customBackgrounds.some(bg => bg === value || generateUrlParameter(bg, true) === value);
}

/**
 * Apply the current background without requiring the retired gallery DOM.
 * @param {string} url
 */
function applyBackgroundVisual(url) {
    $('#bg1').css('background-image', url || 'none');
}

/**
 * Change the persisted global background and update its visual projection.
 * @param {string} name
 * @param {string} [url]
 * @returns {string}
 */
export function setBackground(name, url = '') {
    const nextName = String(name ?? '');
    const nextUrl = url || (nextName ? generateUrlParameter(nextName, false) : '');

    if (!chat_metadata[BG_METADATA_KEY]) {
        applyBackgroundVisual(nextUrl);
    }
    background_settings.name = nextName;
    background_settings.url = nextUrl;
    saveSettingsDebounced();
    return nextName;
}

/**
 * Load the complete historical background settings object. The background
 * gallery no longer owns thumbnail/sort controls, but their saved fields must
 * still round-trip through the settings document.
 * @param {object} settings
 */
export function loadBackgroundSettings(settings) {
    const saved = settings && settings.background;
    if (saved && typeof saved === 'object' && !Array.isArray(saved)) {
        Object.assign(background_settings, saved);
    }

    if (typeof background_settings.name !== 'string') {
        background_settings.name = DEFAULT_BACKGROUND_NAME;
    }
    if (typeof background_settings.url !== 'string') {
        background_settings.url = background_settings.name
            ? generateUrlParameter(background_settings.name, false)
            : '';
    }
    if (typeof background_settings.fitting !== 'string' || !background_settings.fitting) {
        background_settings.fitting = DEFAULT_FITTING;
    }
    if (typeof background_settings.sortOrder !== 'string' || !background_settings.sortOrder) {
        background_settings.sortOrder = DEFAULT_SORT_ORDER;
    }
    if (typeof background_settings.animation !== 'boolean') {
        background_settings.animation = Boolean(background_settings.animation);
    }
    if (!Number.isFinite(Number(background_settings.thumbnailColumns))) {
        background_settings.thumbnailColumns = 5;
    }

    applyBackgroundVisual(background_settings.url);
    setFittingClass(background_settings.fitting);
    $('#background_fitting').val(background_settings.fitting);
}

/**
 * Set a background generated by image-generation flows. This deliberately
 * updates chat metadata only; no gallery or thumbnail node is assumed.
 * @param {{url?: string, path?: string}} backgroundInfo
 * @returns {Promise<void>}
 */
async function forceSetBackground(backgroundInfo) {
    if (!backgroundInfo || typeof backgroundInfo !== 'object') {
        return;
    }

    const url = String(backgroundInfo.url ?? '');
    const path = String(backgroundInfo.path ?? '');
    if (url) {
        chat_metadata[BG_METADATA_KEY] = url;
        applyBackgroundVisual(url);
    }
    if (path) {
        const list = Array.isArray(chat_metadata[LIST_METADATA_KEY])
            ? chat_metadata[LIST_METADATA_KEY]
            : [];
        if (!list.includes(path)) {
            list.push(path);
            chat_metadata[LIST_METADATA_KEY] = list;
        }
    }
    saveMetadataDebounced();
}

/**
 * Apply the chat lock projection when switching chats.
 */
function onChatChanged() {
    applyBackgroundVisual(chat_metadata[BG_METADATA_KEY] || background_settings.url);
}

/**
 * Set the fitting class on the preserved background element.
 * @param {string} fitting
 */
export function setFittingClass(fitting) {
    const normalized = String(fitting || DEFAULT_FITTING);
    const backgrounds = $('#bg1');
    for (const option of ['cover', 'contain', 'stretch', 'center']) {
        backgrounds.toggleClass(option, option === normalized);
    }
    background_settings.fitting = normalized;
}

export function initBackgrounds() {
    eventSource.on(event_types.CHAT_CHANGED, onChatChanged);
    eventSource.on(event_types.FORCE_SET_BACKGROUND, forceSetBackground);

    $('#background_fitting').on('input', function () {
        setFittingClass(String($(this).val()));
        saveSettingsDebounced();
    });
}
