import { test, expect } from '@playwright/test';
import { createServer } from '../node_modules/vite/dist/node/index.js';
import path from 'node:path';
import os from 'node:os';
import { mkdtemp, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
let server, cache, url;
test.beforeAll(async () => { cache = await mkdtemp(path.join(os.tmpdir(), 'regex-f2-')); server = await createServer({ configFile: false, root, publicDir: false, cacheDir: cache, resolve: { alias: { '@': path.join(root, 'app') } }, esbuild: { jsx: 'automatic' }, server: { host: '127.0.0.1', port: 0 } }); await server.listen(); url = `http://127.0.0.1:${server.httpServer.address().port}/tests/regex-editor-fixture.html`; });
test.afterAll(async () => { await server?.close(); if (cache) await rm(cache, { recursive: true, force: true }); });
test.beforeEach(async ({ page }) => { await page.goto(url); });
test('retired placement cannot be selected but remains in historical rules', async ({ page }) => {
    await expect(page.locator('[name=replace_position][value="3"]')).toHaveCount(0);
    await page.goto(`${url}?legacy`);
    await expect(page.locator('[name=replace_position][value="3"]')).toHaveCount(0);
    expect(await page.evaluate(() => window.fixture.editor.current.getDraft().placement)).toEqual([1, 3]);
    await page.locator('[name=replace_position][value="1"]').uncheck();
    await page.locator('[name=replace_position][value="2"]').check();
    expect(await page.evaluate(() => window.fixture.editor.current.validate())).toBe(true);
    expect(await page.evaluate(() => window.fixture.editor.current.getDraft().placement)).toEqual([3, 2]);
});
test('controlled editor validates, exposes draft and runs live test', async ({ page }) => {
    expect(await page.evaluate(() => window.fixture.editor.current.validate())).toBe(false);
    await expect(page.locator('#regex_name_error')).toBeVisible();
    await page.locator('#regex_script_name').fill('Example'); await page.locator('#find_regex').fill('/a/g');
    await page.locator('[name=replace_position][value="1"]').uncheck();
    expect(await page.evaluate(() => window.fixture.editor.current.validate())).toBe(false);
    await expect(page.locator('#regex_placement_error')).toBeVisible();
    await page.locator('[name=replace_position][value="2"]').check();
    expect(await page.evaluate(() => window.fixture.editor.current.validate())).toBe(true);
    expect(await page.evaluate(() => window.fixture.editor.current.getDraft().placement)).toEqual([2]);
    await page.locator('#regex_test_mode_toggle').click(); await page.locator('#regex_test_input').fill('hello');
    await expect(page.locator('#regex_test_output')).toHaveValue('/a/g:hello');
    await expect(page.locator('#regex_info_block')).toContainText('Info Example');
    await page.locator('#find_regex').fill('['); expect(await page.evaluate(() => window.fixture.editor.current.validate())).toBe(false);
    await page.locator('[name=substitute_regex]').selectOption('1'); await page.locator('#find_regex').fill('{{invalid');
    expect(await page.evaluate(() => window.fixture.editor.current.validate())).toBe(true);
});
test('debugger local order, save, test and expansion', async ({ page }) => {
    await page.getByRole('button', { name: 'Move Second up' }).click();
    await page.locator('#regex_debugger_save_order').click();
    await expect.poll(() => page.evaluate(() => window.fixture.calls)).toContainEqual(['reorder', 'global', ['b', 'a']]);
    await expect(page.getByText('Order saved', { exact: true })).toBeVisible();
    await page.locator('#regex_debugger_raw_input').fill('input'); await page.locator('#regex_debugger_run_test').click();
    await expect(page.locator('#regex_debugger_final_output')).toHaveText('input done');
    await page.locator('#regex_debugger_rules_global .rule-enabled').first().uncheck();
    await page.locator('[name=display_mode][value=highlight]').check(); await page.locator('#regex_debugger_render_mode').selectOption('message');
    await page.locator('#regex_debugger_run_test').click();
    const run = await page.evaluate(() => window.fixture.calls.filter(c => c[0] === 'run').at(-1));
    expect(run[1][0].rules.map(rule => rule.id)).toEqual(['a']); expect(run[2]).toEqual({ displayMode: 'highlight', renderMode: 'message' });
    await page.getByRole('button', { name: 'Edit First' }).click();
    await expect.poll(() => page.evaluate(() => window.fixture.calls)).toContainEqual(['debugEditor', 0, 'a']);
    await page.locator('#regex_debugger_expand_steps').click(); await page.locator('#regex_debugger_expand_final').click();
    await expect.poll(() => page.evaluate(() => window.fixture.calls.some(c => c[0] === 'final' && c[1]?.text === 'input done'))).toBe(true);
    await page.evaluate(() => { window.fixture.fail = true; }); await page.locator('#regex_debugger_save_order').click();
    await expect(page.getByText('Order not saved: preset failed')).toBeVisible();
    await page.evaluate(() => window.fixture.debugger.current.refresh());
    await expect(page.locator('#regex_debugger_result_hint')).toBeVisible();
});
test('presets and toolbar dispatch and errors are visible', async ({ page }) => {
    await page.locator('#regex_presets').selectOption('q'); await page.locator('#regex_preset_create').click(); await page.locator('#regex_preset_update').click(); await page.locator('#regex_preset_apply').click(); await page.locator('#regex_preset_delete').click();
    await page.locator('#open_regex_editor').click(); await page.locator('#open_preset_editor').click(); await page.locator('#open_scoped_editor').click(); await page.locator('#open_regex_debugger').click(); await page.locator('#toggle_scoped_regex').click(); await page.locator('#toggle_preset_regex').click();
    await page.locator('#import_regex_file').setInputFiles({ name: 'rules.json', mimeType: 'application/json', buffer: Buffer.from('{}') });
    await expect.poll(() => page.evaluate(() => window.fixture.calls)).toEqual(expect.arrayContaining([['select', 'q'], ['create'], ['update'], ['apply'], ['delete'], ['editor', 0], ['editor', 1], ['editor', 2], ['debugger'], ['scoped', true], ['preset', true], ['import', 1]]));
    await expect(page.locator('#regex_import_target_preset')).toBeDisabled(); await page.locator('#regex_import_target_scoped').check();
    expect(await page.evaluate(() => window.fixture.target.current.getTarget())).toBe('scoped');
    await page.evaluate(() => { window.fixture.fail = true; }); await page.locator('#regex_preset_create').click();
    await expect.poll(() => page.evaluate(() => window.fixture.calls)).toContainEqual(['error', 'preset failed']);
});
